#!/usr/bin/env node

/**
 * Model Context Protocol (MCP) Server for VibeDesign-Harness
 * Exposes UI/UX Aesthetic Linter (for Codex & Gemini) and Studio Image Prompt Engine (for Gemini 3.7 Imagen 3).
 */

import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { CallToolRequestSchema, ListToolsRequestSchema } from '@modelcontextprotocol/sdk/types.js';
import { lintUI, expandPrompt, generateDesignMD } from '../index.js';

const server = new Server(
    {
        name: 'vibe-design-harness-mcp',
        version: '1.0.0',
    },
    {
        capabilities: {
            tools: {},
        },
    }
);

server.setRequestHandler(ListToolsRequestSchema, async () => {
    return {
        tools: [
            {
                name: 'lint_ui_aesthetic',
                description: 'Deterministic zero-token UI/UX aesthetic linter for HTML/Tailwind generated by OpenAI Codex CLI or Gemini 3.7. Detects and purges generic purple gradients, unstyled buttons, and gray backdrops.',
                inputSchema: {
                    type: 'object',
                    properties: {
                        filePath: {
                            type: 'string',
                            description: 'Path to the generated HTML file to audit.',
                        },
                    },
                    required: ['filePath'],
                },
            },
            {
                name: 'expand_image_prompt_gemini',
                description: 'Studio Image Prompt Engine exclusively for Gemini 3.7 (Imagen 3). Bumps raw prompts to match DALL-E 3 / GPT Image 2 photorealism quality by adding 35mm lens physics, studio lighting, depth of field, and negative constraints.',
                inputSchema: {
                    type: 'object',
                    properties: {
                        prompt: {
                            type: 'string',
                            description: 'Raw image prompt concept.',
                        },
                        domain: {
                            type: 'string',
                            description: 'Visual domain style: gemini_imagen_pro (default), photorealism, anime, 3d_animation, infographic, typography_poster, carousel_ad, logo_branding, cover_thumbnail, face_swap_ugc, sales_creative.',
                            default: 'gemini_imagen_pro',
                        },
                    },
                    required: ['prompt'],
                },
            },
            {
                name: 'generate_brand_design_md',
                description: 'Scaffolds Swiss/Linear style DESIGN.md system tokens (colors, typography, component rules) to pre-inject into Codex CLI or Gemini before UI code generation.',
                inputSchema: {
                    type: 'object',
                    properties: {
                        brandName: {
                            type: 'string',
                            description: 'Brand or Project Name (e.g. Linear, Stripe, Vercel).',
                            default: 'Linear',
                        },
                    },
                },
            },
        ],
    };
});

server.setRequestHandler(CallToolRequestSchema, async (request) => {
    const { name, arguments: args } = request;

    if (name === 'lint_ui_aesthetic') {
        const filePath = args.filePath;
        const result = lintUI(filePath);
        return {
            content: [
                {
                    type: 'text',
                    text: JSON.stringify(result, null, 2),
                },
            ],
        };
    }

    if (name === 'expand_image_prompt_gemini') {
        const prompt = args.prompt;
        const domain = args.domain || 'gemini_imagen_pro';
        const result = expandPrompt(prompt, domain);
        return {
            content: [
                {
                    type: 'text',
                    text: JSON.stringify(result, null, 2),
                },
            ],
        };
    }

    if (name === 'generate_brand_design_md') {
        const brandName = args.brandName || 'Linear';
        const doc = generateDesignMD(brandName);
        return {
            content: [
                {
                    type: 'text',
                    text: doc,
                },
            ],
        };
    }

    throw new Error(`Tool not found: ${name}`);
});

async function run() {
    const transport = new StdioServerTransport();
    await server.connect(transport);
}

run().catch((err) => {
    console.error('Fatal MCP error:', err);
    process.exit(1);
});
